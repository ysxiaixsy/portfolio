// Generates the site's pixel art from its sources. Run `npm run pixel-art`
// after changing the portrait or the tech stack, and commit the output:
//   public/portrait-pixel.png  the portrait, shrunk to a small palette
//   src/data/stack-pixels.ts   every stack logo on a 16×16 pixel grid
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import sharp from "sharp";
import ts from "typescript";

const root = resolve(import.meta.dirname, "..");

// Portrait: 64 pixels square, 24 colours, no dithering, so it reads as drawn
// pixel art when scaled up with `image-rendering: pixelated`.
const PORTRAIT_SIZE = 64;
await sharp(join(root, "public/portrait.jpg"))
  .resize(PORTRAIT_SIZE, PORTRAIT_SIZE, { fit: "cover", position: "top" })
  .png({ palette: true, colours: 24, dither: 0 })
  .toFile(join(root, "public/portrait-pixel.png"));

// Stack logos: load the stack from the TypeScript data files by transpiling
// them next to node_modules, so `simple-icons` still resolves.
const cache = join(root, "node_modules/.cache/pixel-art");
mkdirSync(cache, { recursive: true });
for (const name of ["tech-stack", "stack-icons"]) {
  const source = readFileSync(join(root, `src/data/${name}.ts`), "utf8");
  const { outputText } = ts.transpileModule(source, {
    compilerOptions: {
      module: ts.ModuleKind.ESNext,
      target: ts.ScriptTarget.ES2022,
    },
  });
  writeFileSync(
    join(cache, `${name}.mjs`),
    outputText.replaceAll("@/data/stack-icons", "./stack-icons.mjs"),
  );
}
const { stacks } = await import(
  pathToFileURL(join(cache, "tech-stack.mjs")).href
);

// Each logo is drawn at 16×16, and a pixel is filled when the shape covers
// half of it. Logos drawn in thin strokes fill at a third instead, which
// keeps them from breaking up; the rest would clog. Filled pixels merge into
// one path of horizontal runs.
const GRID = 16;
const COVERAGE = 128; // alpha, of 255
const THIN_COVERAGE = 80;
const THIN = new Set(["PostgreSQL", "MySQL", "Figma", "Java"]);
async function pixelate(item) {
  const coverage = THIN.has(item.title) ? THIN_COVERAGE : COVERAGE;
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${item.viewBox ?? "0 0 24 24"}" width="${GRID}" height="${GRID}"><path d="${item.path}" fill="#000"${item.fillRule ? ` fill-rule="${item.fillRule}"` : ""}/></svg>`;
  const { data, info } = await sharp(Buffer.from(svg))
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });
  let path = "";
  for (let y = 0; y < GRID; y++) {
    let x = 0;
    while (x < GRID) {
      const filled = (x) =>
        x < GRID && data[(y * GRID + x) * info.channels + 3] >= coverage;
      if (!filled(x)) {
        x++;
        continue;
      }
      const start = x;
      while (filled(x)) x++;
      path += `M${start} ${y}h${x - start}v1h${start - x}z`;
    }
  }
  return path;
}

const pixels = {};
for (const group of stacks) {
  for (const item of group.items) pixels[item.title] = await pixelate(item);
}

const out = join(root, "src/data/stack-pixels.ts");
mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  `// Generated by scripts/pixel-art.mjs from tech-stack.ts: each logo on a
// ${GRID}×${GRID} pixel grid. Run \`npm run pixel-art\` to update it.
export const STACK_PIXEL_GRID = ${GRID};

export const stackPixels: Record<string, string> = ${JSON.stringify(pixels, null, 2)};
`,
);
console.log(
  `Wrote public/portrait-pixel.png and ${Object.keys(pixels).length} logos to src/data/stack-pixels.ts`,
);
